<?php
declare(strict_types=1);
function brand_text(string $text): string {
    $text=strtr($text,[
        'БЕЛАЯ РАДУГА'=>'ДОМ ЗУБОВ','БЕЛОЙ РАДУГЕ'=>'ДОМЕ ЗУБОВ','БЕЛУЮ РАДУГУ'=>'ДОМ ЗУБОВ',
        'БЕЛОЙ РАДУГИ'=>'ДОМА ЗУБОВ','БЕЛОЙ РАДУГОЙ'=>'ДОМОМ ЗУБОВ',
    ]);
    return preg_replace(
        ['/белая\s+радуга/ui','/белой\s+радуге/ui','/белую\s+радугу/ui','/белой\s+радуги/ui','/белой\s+радугой/ui','/Belaya\s+Raduga/i'],
        ['Дом Зубов','Доме Зубов','Дом Зубов','Дома Зубов','Домом Зубов','Dom Zubov'],$text
    );
}
